/* ---------- 로드 시 1회 인덱스 생성 ---------- */
var WORDCHAIN_WORDS = [];      /* 전체 낱말 배열 */
var WORDCHAIN_CAT_OF = {};     /* 낱말 -> 카테고리 id */
var WORDCHAIN_BY_FIRST = {};   /* 첫 글자 -> 낱말 배열 */

(function buildWordChainIndex() {
  var cid, list, i, w, ch;
  for (cid in WORDCHAIN_RAW) {
    if (!WORDCHAIN_RAW.hasOwnProperty(cid)) continue;
    list = WORDCHAIN_RAW[cid].split(" ");
    for (i = 0; i < list.length; i++) {
      w = list[i];
      if (w.length < 2) continue;
      if (WORDCHAIN_CAT_OF[w] !== undefined) continue;   /* 중복 제거 */
      WORDCHAIN_CAT_OF[w] = parseInt(cid, 10);
      WORDCHAIN_WORDS.push(w);
      ch = w.charAt(0);
      if (!WORDCHAIN_BY_FIRST[ch]) WORDCHAIN_BY_FIRST[ch] = [];
      WORDCHAIN_BY_FIRST[ch].push(w);
    }
  }
})();
